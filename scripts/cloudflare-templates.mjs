import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import Handlebars from 'handlebars'
const root = fileURLToPath(new URL('../apps/backend/templates/email/', import.meta.url))
const files = {}
async function walk(dir) {
  for (const entry of (await readdir(dir, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) await walk(full)
    else if (/\.(json|hbs|html)$/i.test(entry.name)) files[`/templates/email/${path.relative(root, full).split(path.sep).join('/')}`] = await readFile(full, 'utf8')
  }
}
await walk(root)
const target = new URL('../apps/backend/src/generated/emailTemplates.json', import.meta.url)
await mkdir(new URL('.', target), { recursive: true })
await writeFile(target, JSON.stringify(files, null, 2) + '\n')

const precompiledEntries = Object.entries(files)
  .filter(([filePath]) => /\.(hbs|html)$/i.test(filePath))
  .map(([filePath, source]) => {
    const specification = Handlebars.precompile(source, {
      noEscape: false,
      strict: false,
    })
    return `  ${JSON.stringify(filePath)}: ${specification},`
  })

const precompiledTarget = new URL('../apps/backend/src/generated/emailTemplateSpecs.ts', import.meta.url)
await writeFile(
  precompiledTarget,
  [
    '// Generated by scripts/cloudflare-templates.mjs. Do not edit by hand.',
    '// @ts-nocheck -- Handlebars emits positional runtime callbacks with intentionally unused parameters.',
    "import HandlebarsRuntime from 'handlebars/runtime'",
    '',
    'type TemplateSpecification = Parameters<typeof HandlebarsRuntime.template>[0]',
    '',
    'const precompiledTemplateSpecs: Record<string, TemplateSpecification> = {',
    ...precompiledEntries,
    '}',
    '',
    'export function hasPrecompiledEmailTemplate(templatePath: string): boolean {',
    '  return precompiledTemplateSpecs[templatePath] !== undefined',
    '}',
    '',
    'export function renderPrecompiledEmailTemplate(',
    '  templatePath: string,',
    '  context: unknown,',
    '  partialPaths: Record<string, string> = {},',
    '): string {',
    '  const specification = precompiledTemplateSpecs[templatePath]',
    '  if (!specification) throw new Error(`Precompiled email template not found: ${templatePath}`)',
    '  const runtime = HandlebarsRuntime.create()',
    '  for (const [name, partialPath] of Object.entries(partialPaths)) {',
    '    const partialSpecification = precompiledTemplateSpecs[partialPath]',
    '    if (!partialSpecification) throw new Error(`Precompiled email template partial not found: ${partialPath}`)',
    '    runtime.registerPartial(name, runtime.template(partialSpecification))',
    '  }',
    '  return runtime.template(specification)(context)',
    '}',
    '',
  ].join('\n'),
)

console.info(
  `Bundled ${Object.keys(files).length} email template files and precompiled ${precompiledEntries.length} renderable templates`,
)
